export function getTemplateById(id: TemplateId): TemplateDefinition {
  return CV_TEMPLATES.find((t) => t.id === id) ?? CV_TEMPLATES[0];
}

export function filterTemplates(
  category: 'All' | TemplateCategory,
  searchQuery = ''
): TemplateDefinition[] {
  const q = searchQuery.trim().toLowerCase();
  return CV_TEMPLATES.filter((tpl) => {
    const matchesCategory = category === 'All' || tpl.category === category;
    if (!matchesCategory) return false;
    if (!q) return true;
    return (
      tpl.name.toLowerCase().includes(q) ||
      tpl.category.toLowerCase().includes(q) ||
      tpl.description.toLowerCase().includes(q) ||
      tpl.layoutTag.toLowerCase().includes(q) ||
      (tpl.occupations ?? []).some((occ) => occ.toLowerCase().includes(q))
    );
  });
}
